export async function seedAutomation(prisma: PrismaClient) {
  for (const rule of DEFAULT_SLA_RULES) {
    await prisma.slaRule.upsert({
      where: { key: rule.key },
      create: { ...rule },
      update: {
        name: rule.name,
        description: rule.description,
        moduleKey: rule.moduleKey,
        unit: rule.unit,
        targetValue: rule.targetValue,
        loadType: "loadType" in rule ? rule.loadType : null,
        sortOrder: rule.sortOrder,
        active: true,
      },
    });
  }

  for (const rule of DEFAULT_NOTIFICATION_RULES) {
    await prisma.notificationRule.upsert({
      where: { triggerKey: rule.triggerKey },
      create: {
        ...rule,
        escalateAfterHours: "escalateAfterHours" in rule ? rule.escalateAfterHours : null,
        slaKey: "slaKey" in rule ? rule.slaKey : null,
      },
      update: {
        name: rule.name,
        description: rule.description,
        moduleKey: rule.moduleKey,
        action: rule.action,
        severity: rule.severity,
        recipientRoles: rule.recipientRoles,
        channels: rule.channels,
        dedupeHours: rule.dedupeHours,
        slaKey: "slaKey" in rule ? rule.slaKey : null,
        escalateAfterHours: "escalateAfterHours" in rule ? rule.escalateAfterHours : null,
        sortOrder: rule.sortOrder,
        active: true,
      },
    });
  }
}
